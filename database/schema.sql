CREATE DATABASE IF NOT EXISTS ucu_lost_found CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE ucu_lost_found;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, full_name VARCHAR(150) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE, student_number VARCHAR(60) NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role ENUM('student','admin') NOT NULL DEFAULT 'student',
 phone VARCHAR(40), course VARCHAR(120), bio TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(180) NOT NULL, description TEXT NOT NULL, category VARCHAR(80) NOT NULL,
 item_type ENUM('lost','found') NOT NULL, location VARCHAR(180) NOT NULL, event_date DATE NOT NULL,
 image_url TEXT, status ENUM('open','claimed','returned','closed') DEFAULT 'open',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS claims (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, item_id BIGINT UNSIGNED NOT NULL,
 claimant_id BIGINT UNSIGNED NOT NULL, message TEXT NOT NULL,
 status ENUM('pending','approved','rejected') DEFAULT 'pending',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(item_id) REFERENCES items(id) ON DELETE CASCADE,
 FOREIGN KEY(claimant_id) REFERENCES users(id) ON DELETE CASCADE,
 UNIQUE KEY uq_claim(item_id,claimant_id)
);
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 message VARCHAR(500) NOT NULL, is_read BOOLEAN DEFAULT FALSE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
